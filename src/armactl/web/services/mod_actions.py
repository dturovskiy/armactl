def export_active_mods_json(
    *,
    instance: str = paths.DEFAULT_INSTANCE_NAME,
) -> tuple[ModActionResult, bytes]:
    """Return active mods as exported JSON without writing an export file."""
    normalized_instance = instance or paths.DEFAULT_INSTANCE_NAME
    try:
        config_path = _config_path(normalized_instance)
        active_mods = mods_manager.get_mods(config_path)
    except (ModActionError, ConfigError) as error:
        return (
            _failure(
                action=ACTION_EXPORT,
                instance=normalized_instance,
                target="active mods export",
                message=error,
            ),
            b"",
        )

    content = (json.dumps(active_mods, indent=4) + "\n").encode("utf-8")
    return (
        _result(
            action=ACTION_EXPORT,
            instance=normalized_instance,
            target="active mods export",
            success=True,
            changed=False,
            message=f"Exported {len(active_mods)} active mod(s).",
            exit_code=0,
            details={"exported_count": str(len(active_mods))},
        ),
        content,
    )


def add_or_update_mod(
    *,
    instance: str = paths.DEFAULT_INSTANCE_NAME,
    mod_id: str,
    name: str = "",
    version: str = "",
) -> ModActionResult:
    """Add, update, or reactivate one Workshop mod through mods_manager."""
    normalized_instance = instance or paths.DEFAULT_INSTANCE_NAME
    try:
        reference = _mod_id(mod_id)
        mod_name = _validated_optional_text(name, message="Mod name is invalid.")
        mod_version = _validated_optional_text(version, message="Mod version is invalid.")
        config_path = _config_path(normalized_instance)
        target_label = _mod_target_label(
            reference,
            mod_name or _existing_mod_name(config_path, reference),
        )
        result = mods_manager.add_mod_detailed(
            config_path,
            reference,
            mod_name,
            mod_version,
        )
    except (ModActionError, ConfigError) as error:
        return _failure(
            action=ACTION_ADD,
            instance=normalized_instance,
            target=mod_id,
            message=error,
        )

    if result.status == "added":
        return _result(
            action=ACTION_ADD,
            instance=normalized_instance,
            target=reference,
            success=True,
            changed=True,
            message="Mod added.",
            exit_code=0,
            details={"mod_label": target_label},
        )
    if result.status == "updated":
        return _result(
            action=ACTION_UPDATE,
            instance=normalized_instance,
            target=reference,
            success=True,
            changed=True,
            message="Mod updated.",
            exit_code=0,
            details={"mod_label": target_label},
        )
    if result.status == "reactivated":
        return _result(
            action=ACTION_ENABLE,
            instance=normalized_instance,
            target=reference,
            success=True,
            changed=True,
            message="Mod enabled.",
            exit_code=0,
            details={"mod_label": target_label},
        )
    return _result(
        action=ACTION_ADD,
        instance=normalized_instance,
        target=reference,
        success=True,
        changed=False,
        message="Mod was unchanged.",
        exit_code=0,
        details={"mod_label": target_label},
    )


