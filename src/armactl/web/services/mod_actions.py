def _normalize_import_mode(value: object) -> str:
    mode = str(value or "").strip().lower()
    if mode in {"", IMPORT_MODE_APPEND}:
        return IMPORT_MODE_APPEND
    if mode == IMPORT_MODE_REPLACE:
        return IMPORT_MODE_REPLACE
    raise ModActionError("Import mode is invalid.")


